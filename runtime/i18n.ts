export function isSupported(locale: string) {
  return Object.hasOwn(CATALOGS, locale);
}

export function translate(locale: string, code: string, params: Record<string, unknown> = {}) {
  const template = CATALOGS[locale]?.[code] ?? CATALOGS[DEFAULT_LOCALE][code] ?? code;
  return template.replace(/\{(\w+)\}/g, (_, key) => String(params[key] ?? `{${key}}`));
}

// Attach a localized message to every `{ code, ...params }` issue without changing its code.
export function localize<T extends { code: string }>(locale: string, issues: T[]) {
  return issues.map((issue) => ({ ...issue, message: translate(locale, issue.code, issue) }));
}
