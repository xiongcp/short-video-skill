// Fixture aligner: one word per narration character over 97% of the section, leaving a short tail pause.
function engineWords(section, samples) {
  const chars = [...normalize(section.narration)];
  const span = Math.floor(samples * 0.97);
  return chars.map((text, i) => ({ text, start_sample: Math.floor((i * span) / chars.length), end_sample: Math.floor(((i + 1) * span) / chars.length), confidence: 0.95 }));
}

// Draft project up to ALIGNMENT_READY from an example's brief, evidence and script.
function draftToAlignment(c, id, example, durations, measured) {
  const brief = json(`examples/${example}/brief.json`), evidence = json(`examples/${example}/evidence-set.json`), script = json(`examples/${example}/script.json`);
  c.call('init', 'init', { project_id: id, title: brief.topic, mode: 'draft' });
  c.call('brief', 'brief', { ...c.envelope('brief'), topic: brief.topic, audience: brief.audience, scope: brief.scope, keywords: brief.keywords,
    language: brief.language, style_profile: brief.style_profile, overrides: durations });
  c.event('research_started');
  c.call('evidence', 'evidence', { ...c.envelope('evidence'), sources: evidence.sources,
    claims: evidence.claims.map(({ claim_id, statement, qualifier }) => ({ claim_id, statement, qualifier })), links: evidence.claim_source_links });
  c.event('draft_script_requested');
  c.call('script', 'script', { ...c.envelope('script'), script_id: script.script_id, sections: script.sections });
  c.event('draft_audio_requested');
  const voice = `asset://${id}/host_voice/v1`;
  const takes = script.sections.map((section, k) => ({ section, samples: measured(section, k) }));
  const audio = c.call('audio', 'audio', { ...c.envelope('audio'), sections: takes.map(({ section, samples }) => ({ section_id: section.section_id,
    import: { path: c.file(`${section.section_id}.wav`, wavBytes({ seconds: samples / 48000 })), recordist: 'fixture', voice_ref: voice } })) });
  const alignment = c.call('align', 'align', { ...c.envelope('align'), audio_version: 1, engine: { name: 'fixture-per-character', version: '1.0' },
    sections: takes.map(({ section, samples }) => ({ section_id: section.section_id, words: engineWords(section, samples) })), subtitle_style_ref: `asset://${id}/subtitle_style/v1` });
  return { script, audio, alignment };
}

// Register the example's asset catalog with placeholder bytes, clear it as the owner and build its scenes from templates.
function registerCatalog(c, dir, example) {
  const catalog = json(`examples/${example}/assets.json`);
  const owner = { SVS_SESSION_TOKEN: createSession(dir, { reviewer_id: 'owner', kind: 'human' }) };
  const name = (ref) => ref.split('/')[3];
  const elements = new Map(catalog.scenes.flatMap((s) => s.layers.map((l) => [l.asset_ref, l.element_ids])));
  const grid = (ids) => ({ elements: ids.map((element_id, i) => {
    const col = i % 3, row = Math.floor(i / 3) % 2;
    return { element_id, box: { left: 0.2 + col * 0.2, top: 0.3 + row * 0.2, right: 0.35 + col * 0.2, bottom: 0.45 + row * 0.2 } };
  }) });
  const bytes = {
    background: (n) => c.file(`${n}.png`, pngBytes(2880, 1620)),
    illustration: (n) => c.file(`${n}.png`, pngBytes(2880, 1620, [240, 200, 60, 255])),
    diagram: (n, ref) => c.file(`${n}.json`, JSON.stringify(grid(elements.get(ref) ?? []))),
    rig: (n) => c.file(`${n}.json`, JSON.stringify({ rig: 'fixture', parameters: ['ParamMouthOpenY'] })),
    voice: (n) => c.file(`${n}.wav`, wavBytes({ seconds: 1 })),
    character: (n) => c.file(`${n}.png`, pngBytes(1200, 1600, [200, 120, 90, 255])),
  };
  for (const asset of catalog.assets.filter((a) => a.kind !== 'scene')) {
    const n = name(asset.ref);
    const character = catalog.characters.find((ch) => ch.character_ref === asset.ref);
    const profile = character && (({ project_id, version, character_ref, ...rest }) => rest)(character);
    c.call(`register-${n}`, 'register', { project_id: catalog.project_id, name: n, kind: asset.kind, path: bytes[asset.kind](n, asset.ref), rights: RIGHTS, ...(profile && { profile }) });
    c.call(`clear-${n}`, 'clear', { project_id: catalog.project_id, asset_ref: asset.ref, usage: 'cleared', notes: '代码生成的占位素材，权利归项目所有者' }, owner, 'human:owner');
  }
  for (const scene of catalog.scenes) {
    c.call(`scene-${name(scene.scene_ref)}`, 'scene', { project_id: catalog.project_id, name: name(scene.scene_ref), template: scene.template, focus: scene.focus, props: scene.props,
      layers: scene.layers.map((l) => ({ asset_ref: l.asset_ref, element_ids: l.element_ids, ...(l.claim_ids && { claim_ids: l.claim_ids }) })) });
  }
}

// Aligned copy of a planned board: the first shot of a section cuts on the section start, later shots on the word at the
// same proportional position; planned visual cues stay at their fixed local frames; host shots inherit the previous host
// shot of the same chapter.
function directorCopy(board, alignment) {
  const spans = new Map();
  for (const s of board.shots) {
    const span = spans.get(s.section_id) ?? { start: s.frame_range.start, end: s.frame_range.end };
    spans.set(s.section_id, { start: Math.min(span.start, s.frame_range.start), end: Math.max(span.end, s.frame_range.end) });
  }
  const words = (sid) => alignment.alignment.tokens.filter((t) => t.section_id === sid);
  const lastHost = new Map();
  return {
    alignment_version: alignment.alignment.version,
    chapters: board.chapters.map(({ frame_range, ...chapter }) => chapter),
    shots: board.shots.map((s) => {
      const span = spans.get(s.section_id), own = words(s.section_id);
      const start = s.frame_range.start === span.start ? { section_id: s.section_id }
        : { word_id: own[Math.min(own.length - 1, Math.round(((s.frame_range.start - span.start) / (span.end - span.start)) * own.length))].word_id, edge: 'start' };
      const depends_on = s.character_actions.length && lastHost.get(s.chapter_id) ? [lastHost.get(s.chapter_id)] : [];
      if (s.character_actions.length) lastHost.set(s.chapter_id, s.shot_id);
      return { shot_id: s.shot_id, chapter_id: s.chapter_id, section_id: s.section_id, start, purpose: s.purpose, camera: s.camera, zoom: s.camera === 'push_in' ? 1.2 : 1,
        scene_ref: s.scene_ref, scene_layers: s.scene_layers, character_actions: s.character_actions, audio_anchors: s.audio_anchors,
        visual_cues: s.visual_cues.map(({ at_local_frame, ...cue }) => ({ ...cue, at: { local_frame: at_local_frame } })), depends_on };
    }),
  };
}

function snapshot(dir, label) {
  const db = new DatabaseSync(join(dir, 'studio.sqlite'));
  const assets = db.prepare('SELECT asset_ref, kind, path, sha256 FROM assets').all();
  mkdirSync(join(out, label), { recursive: true });
  db.exec(`VACUUM INTO '${join(out, label, 'studio.sqlite')}'`);
  db.close();
  return new Map(assets.map((a) => [a.asset_ref, { ...a, file_matches: sha256(readFileSync(join(dir, a.path))) === a.sha256 }]));
}

