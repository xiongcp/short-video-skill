// One CLI client per project; large documents are saved once on their own and referenced by hash in the audit.
function client(dir, prefix) {
  const call = (label, op, request, env = {}, session = null) => {
    const seq = audit.length;
    const run = runCli([op, '--project', dir, '--request', writeJson(join(dir, 'requests', `${seq}.json`), request)], env);
    const response = run.json?.document ? { ...run.json, document: `<saved separately; content_hash ${run.json.content_hash}>` } : run.json;
    const entry = { seq, label: `${prefix}/${label}`, op, session, request: op === 'align' || op === 'storyboard' ? `<request sha256 ${sha256(JSON.stringify(request))}>` : request,
      exit_code: run.code, response };
    writeFileSync(join(out, 'audit', `${String(seq).padStart(3, '0')}-${prefix}-${label}.json`), JSON.stringify(entry, null, 2) + '\n');
    audit.push(entry);
    return run.json;
  };
  const version = () => call('status', 'status', { project_id: projectOf(dir) }).version;
  const envelope = (key) => ({ project_id: projectOf(dir), expected_version: version(), idempotency_key: key });
  const event = (name) => call(name, 'event', { ...envelope(name), event: name, payload: {} });
  const file = (name, bytes) => {
    mkdirSync(join(dir, 'incoming'), { recursive: true });
    writeFileSync(join(dir, 'incoming', name), bytes);
    fixtures[`${prefix}/${name}`] = sha256(bytes);
    return `incoming/${name}`;
  };
  return { call, envelope, event, file };
}
