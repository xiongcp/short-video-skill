// Rebuild A06 runtime evidence: register code-generated fixture art with rights, clear usage through a simulated owner session,
// build host/diagram/illustration scenes from templates, and run formal-assembly preflight (positive and negative).
// Not covered: original anime art, the 45–60 s art sample, three-background screenshots and the human art decision.
// usage: node docs/upgrade/evidence/replay_t06.mjs <run_id> [python]
import { spawnSync } from 'node:child_process';
import { createHash } from 'node:crypto';
import { mkdirSync, readFileSync, readdirSync, rmSync, statSync, writeFileSync } from 'node:fs';
import { basename, join, relative } from 'node:path';
import { DatabaseSync } from 'node:sqlite';
import { ROOT, makeProject, pngBytes, runCli, wavBytes, writeJson } from '../../../tests/runtime/helpers.mjs';
import { createSession } from '../../../runtime/approvals.ts';

const [runId, python = 'python3'] = process.argv.slice(2);
if (!runId) throw new Error('usage: replay_t06.mjs <run_id> [python]');
const out = join(ROOT, 'docs', 'upgrade', 'evidence', 'runs', runId, 'A06');
rmSync(out, { recursive: true, force: true });
mkdirSync(join(out, 'audit'), { recursive: true });
const sha256 = (data) => 'sha256:' + createHash('sha256').update(data).digest('hex');
const save = (name, value) => writeFileSync(join(out, name), typeof value === 'string' ? value : JSON.stringify(value, null, 2) + '\n');

const ID = 'host-demo';
const ref = (name, v = 1) => `asset://${ID}/${name}/v${v}`;
const dir = makeProject();
const audit = [];
function call(label, op, request, env = {}, session = null) {
  const seq = audit.length;
  const run = runCli([op, '--project', dir, '--request', writeJson(join(dir, 'requests', `${seq}.json`), request)], env);
  const entry = { seq, label, op, session, request, exit_code: run.code, response: run.json };
  writeFileSync(join(out, 'audit', `${String(seq).padStart(3, '0')}-${label}.json`), JSON.stringify(entry, null, 2) + '\n');
  audit.push(entry);
  return run.json;
}
const fixtures = {};
function file(name, bytes) {
  mkdirSync(join(dir, 'incoming'), { recursive: true });
  writeFileSync(join(dir, 'incoming', name), bytes);
  fixtures[name] = sha256(bytes);
  return `incoming/${name}`;
}
const RIGHTS = { holder: 'project owner', license: 'owner-original', source: 'fixture generated by replay_t06.mjs (solid-colour placeholder, not character art)', original: true };
const register = (label, name, kind, path, extra = {}) => call(label, 'register', { project_id: ID, name, kind, path, rights: RIGHTS, ...extra });
const PROFILE = (rig) => ({ character_id: 'host_main', style_lock: ['墨蓝短外套', '栗色齐肩发', '琥珀色发夹的位置固定'], rig_ref: rig, voice_ref: ref('host_voice'),
  supported_angles: ['front', 'three_quarter'], expressions: ['neutral', 'curious', 'explaining'], gestures: ['idle', 'explain', 'point_right'],
  parameters: [{ parameter_id: 'ParamMouthOpenY', min: 0, max: 1 }] });
const DIAGRAM = { elements: [{ element_id: 'browser', box: { left: 0.15, top: 0.3, right: 0.35, bottom: 0.55 } }, { element_id: 'server', box: { left: 0.65, top: 0.3, right: 0.85, bottom: 0.55 } }] };
const action = (angle, character = ref('host_main')) => ({ character_ref: character, angle, expression: 'explaining', gesture: 'point_right', gaze: 'camera' });

call('init', 'init', { project_id: ID, title: '主持人素材', mode: 'quality' });
const owner = { SVS_SESSION_TOKEN: createSession(dir, { reviewer_id: 'owner', kind: 'human' }) };
const bot = { SVS_SESSION_TOKEN: createSession(dir, { reviewer_id: 'writer-bot', kind: 'agent' }) };
register('register-backdrop', 'studio_backdrop', 'background', file('backdrop-2880x1620.png', pngBytes(2880, 1620)));
register('register-backdrop-hd', 'backdrop_hd', 'background', file('backdrop-1920x1080.png', pngBytes(1920, 1080)));
register('register-rig', 'host_rig', 'rig', file('rig.json', JSON.stringify({ rig: 'fixture', parameters: ['ParamMouthOpenY'] })));
register('register-voice', 'host_voice', 'voice', file('voice.wav', wavBytes({ seconds: 1 })));
register('register-host', 'host_main', 'character', file('host.png', pngBytes(1200, 1600, [200, 120, 90, 255])), { profile: PROFILE(ref('host_rig')) });
register('register-host-alt-missing-rig', 'host_alt', 'character', file('host-alt.png', pngBytes(1200, 1600, [180, 110, 80, 255])), { profile: PROFILE(ref('host_rig', 2)) });
register('register-diagram', 'diagram_cache', 'diagram', file('diagram.json', JSON.stringify(DIAGRAM)));
register('register-illustration', 'layer_illustration', 'illustration', file('illustration.png', pngBytes(2880, 1620, [240, 200, 60, 255])));
register('register-pending', 'backdrop_pending', 'background', file('pending.png', pngBytes(2880, 1620, [20, 20, 20, 255])));
const agentClear = call('clear-by-agent', 'clear', { project_id: ID, asset_ref: ref('studio_backdrop'), usage: 'cleared', notes: '' }, bot, 'agent:writer-bot');
for (const name of ['studio_backdrop', 'backdrop_hd', 'host_rig', 'host_voice', 'host_main', 'host_alt', 'diagram_cache', 'layer_illustration']) {
  call(`clear-${name}`, 'clear', { project_id: ID, asset_ref: ref(name), usage: 'cleared', notes: '代码生成的测试素材，权利归项目所有者' }, owner, 'human:owner');
}
const replay = register('register-backdrop-again', 'studio_backdrop', 'background', 'incoming/backdrop-2880x1620.png');
const v2 = register('register-backdrop-v2', 'studio_backdrop', 'background', file('backdrop-v2.png', pngBytes(2880, 1620, [60, 80, 120, 255])));

const scene = (label, name, template, focus, layers) => call(label, 'scene', { project_id: ID, name, template, focus, layers });
const host = scene('scene-host', 'studio_host', 'host', '主持人双眼和手势', [{ asset_ref: ref('studio_backdrop') }]);
const diagram = scene('scene-diagram', 'diagram_ch_002', 'diagram', '浏览器和服务器分列两端',
  [{ asset_ref: ref('studio_backdrop') }, { asset_ref: ref('diagram_cache'), element_ids: ['browser', 'server'], claim_ids: ['reuse'] }]);
const illustration = scene('scene-illustration', 'illustration_ch_001', 'illustration', '两扇浏览器窗口', [{ asset_ref: ref('studio_backdrop') }, { asset_ref: ref('layer_illustration'), element_ids: ['beat_002'] }]);
scene('scene-hd', 'studio_hd', 'host', '1080p 背景', [{ asset_ref: ref('backdrop_hd') }]);
scene('scene-pending', 'studio_pending', 'host', '待授权背景', [{ asset_ref: ref('backdrop_pending') }]);
const mismatch = scene('scene-wrong-layer', 'diagram_bad', 'diagram', '错层', [{ asset_ref: ref('studio_backdrop') }, { asset_ref: ref('layer_illustration') }]);

const preflight = (label, shots) => call(label, 'preflight', { project_id: ID, shots });
const negative = preflight('preflight-negative', [
  { shot_id: 'shot_001', scene_ref: ref('studio_host'), character: action('front', ref('host_alt')), camera: { zoom: 1 } },
  { shot_id: 'shot_002', scene_ref: ref('studio_pending'), camera: { zoom: 1 } },
  { shot_id: 'shot_003', scene_ref: ref('studio_host'), character: action('side_90'), camera: { zoom: 1 } },
  { shot_id: 'shot_004', scene_ref: ref('studio_hd'), camera: { zoom: 1.5 } },
  { shot_id: 'shot_005', scene_ref: ref('diagram_ch_002'), camera: { zoom: 1.5 } },
]);
const positive = preflight('preflight-positive', [
  { shot_id: 'shot_host', scene_ref: ref('studio_host'), character: action('three_quarter'), camera: { zoom: 1.5 } },
  { shot_id: 'shot_diagram', scene_ref: ref('diagram_ch_002'), camera: { zoom: 1 } },
  { shot_id: 'shot_illustration', scene_ref: ref('illustration_ch_001'), camera: { zoom: 1.2 } },
  { shot_id: 'shot_hd_static', scene_ref: ref('studio_hd'), camera: { zoom: 1 } },
]);

// AssetCatalog view of the registry, validated against the existing contract.
const db = new DatabaseSync(join(dir, 'studio.sqlite'));
const rows = db.prepare('SELECT asset_ref, kind, sha256, meta FROM assets ORDER BY asset_ref').all();
const usage = (r) => db.prepare('SELECT usage FROM asset_usage WHERE asset_ref = ? ORDER BY rowid DESC LIMIT 1').get(r)?.usage ?? 'pending';
const catalog = {
  project_id: ID, version: 1,
  assets: rows.map((r) => ({ ref: r.asset_ref, kind: r.kind, state: 'available', hash: r.sha256, usage: usage(r.asset_ref) })),
  characters: positive.resolved.filter((s) => s.character).map((s) => s.character).slice(0, 1),
  scenes: [host.scene, diagram.scene, illustration.scene],
};
const tables = {
  assets: rows.map((r) => ({ ...r, meta: JSON.parse(r.meta) })),
  asset_usage: db.prepare('SELECT asset_ref, usage, reviewer_id, notes, recorded_at FROM asset_usage ORDER BY rowid').all(),
};
db.exec(`VACUUM INTO '${join(out, 'studio.sqlite')}'`);
db.close();
rmSync(dir, { recursive: true, force: true });
save('asset-catalog.json', catalog);
save('tables.json', tables);
save('preflight-negative.json', negative);
save('preflight-positive.json', positive);
save('scenes.json', catalog.scenes);

const check = spawnSync(python, ['-B', '-c', [
  'import json, sys', "sys.path.insert(0, 'evals')", 'from check_design import read_schemas, validate_contract', 'schemas, registry = read_schemas()',
  `catalog = json.load(open(${JSON.stringify(relative(ROOT, join(out, 'asset-catalog.json')))}))`,
  "validate_contract(catalog, 'workflow#AssetCatalog', schemas, registry); print('asset-catalog.json valid against workflow#AssetCatalog')",
  "[validate_contract(s, 'scene', schemas, registry) for s in catalog['scenes']]; print(f\"{len(catalog['scenes'])} scenes valid against scene\")",
  "[validate_contract(c, 'character', schemas, registry) for c in catalog['characters']]; print(f\"{len(catalog['characters'])} character profile valid against character\")",
].join('\n')], { cwd: ROOT, encoding: 'utf8' });
save('schema-check.txt', check.stdout + check.stderr);

const codes = (r) => JSON.stringify(r.issues.map((i) => [i.code, i.shot_id, i.asset_ref, i.element_id ?? i.angle ?? null]));
const checks = {
  negative_named: codes(negative) === JSON.stringify([
    ['ASSET_NOT_FOUND', 'shot_001', ref('host_rig', 2), null], ['ASSET_NOT_CLEARED', 'shot_002', ref('backdrop_pending'), null],
    ['ANGLE_UNREGISTERED', 'shot_003', ref('host_main'), 'side_90'], ['COVERAGE_INSUFFICIENT', 'shot_004', ref('backdrop_hd'), null],
    ['ELEMENT_OUTSIDE_SAFE_AREA', 'shot_005', ref('diagram_cache'), 'browser'], ['ELEMENT_OUTSIDE_SAFE_AREA', 'shot_005', ref('diagram_cache'), 'server']]),
  coverage_numbers: negative.issues[3].required_width === 2880 && negative.issues[3].required_height === 1620,
  positive_ready: positive.status === 'READY' && positive.resolved.every((s) => s.assets.every((a) => a.usage === 'cleared' && /^sha256:/.test(a.sha256))),
  host_pins_rig_voice: JSON.stringify(positive.resolved[0].assets.map((a) => a.kind)) === '["scene","background","character","rig","voice"]',
  clearance_human_only: agentClear.issues[0]?.code === 'HUMAN_REQUIRED',
  versions_retained: replay.status === 'REPLAYED' && v2.asset.asset_ref === ref('studio_backdrop', 2) && v2.asset.usage === 'pending'
    && positive.resolved[0].assets[1].asset_ref === ref('studio_backdrop'),
  template_kind_enforced: mismatch.issues[0]?.code === 'LAYER_KIND_MISMATCH',
  schemas_valid: check.status === 0,
};
const files = (d) => readdirSync(d).flatMap((name) => statSync(join(d, name)).isDirectory() ? files(join(d, name)) : [join(d, name)]);
const record = {
  task_id: 'T06', case_id: 'A06', run_id: runId, status: Object.values(checks).every(Boolean) ? 'PASS' : 'FAIL', evidence_level: 'RUNTIME',
  environment: { node: process.version, platform: `${process.platform}-${process.arch}`, python: spawnSync(python, ['--version'], { encoding: 'utf8' }).stdout.trim() },
  commands_and_exit_codes: [
    { command: `node docs/upgrade/evidence/replay_t06.mjs ${runId} ${basename(python)}`, note: 'each CLI call is saved under audit/ with request, exit code and response' },
    { command: `${basename(python)} -B -c <validate AssetCatalog, scenes and character profile>`, exit_code: check.status, saved_as: 'schema-check.txt' },
  ],
  input_hashes: [...['schemas/character.schema.json', 'schemas/scene.schema.json', 'policies/content-safety.yaml'].map((path) => ({ path, sha256: sha256(readFileSync(join(ROOT, path))) })),
    ...Object.entries(fixtures).map(([name, hash]) => ({ path: `fixture incoming/${name}`, sha256: hash }))],
  output_hashes: files(out).map((path) => ({ path: relative(out, path), sha256: sha256(readFileSync(path)) })),
  observations: [
    `checks: ${JSON.stringify(checks)}`,
    'all bitmaps are solid-colour PNGs generated in code; they exercise registration, rights, versions, coverage and safe-area checks only',
    'scope: original anime host art, layered PSD and rig, the 45–60 s art sample, dark/light/checkerboard screenshots, hair-halo and sleeve inspection, extreme poses and the human art decision (A06/A11) are NOT_RUN; clearance sessions are created by this script',
  ],
  evidence_paths: files(out).map((path) => relative(ROOT, path)),
  reviewer: null,
};
save('record.json', record);
console.log(JSON.stringify({ status: record.status, checks, calls: audit.length }));
