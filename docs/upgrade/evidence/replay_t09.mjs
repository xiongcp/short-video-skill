// Decode video frames (sampled positions) + full PCM audio from an MP4 to compare recovered vs clean outputs.
function decodeDigest(mp4Path, sampleFrames) {
  const probe = JSON.parse(spawnSync('ffprobe', ['-v', 'error', '-count_frames', '-show_entries',
    'stream=codec_type,codec_name,width,height,pix_fmt,sample_rate,nb_read_frames', '-of', 'json', mp4Path], { encoding: 'utf8' }).stdout);
  const v = probe.streams.find((s) => s.codec_type === 'video');
  const a = probe.streams.find((s) => s.codec_type === 'audio');
  const frames = {};
  for (const n of sampleFrames) {
    const raw = spawnSync('ffmpeg', ['-v', 'error', '-i', mp4Path, '-vf', `select=eq(n\\,${n})`, '-fps_mode', 'passthrough',
      '-frames:v', '1', '-f', 'rawvideo', '-pix_fmt', 'rgb24', 'pipe:1'], { maxBuffer: 16 * 1024 * 1024 });
    frames[n] = sha256(raw.stdout);
  }
  const pcm = spawnSync('ffmpeg', ['-v', 'error', '-i', mp4Path, '-vn', '-f', 's16le', '-ac', '2', '-ar', '48000', 'pipe:1'],
    { maxBuffer: 64 * 1024 * 1024 });
  return {
    video_frames: Number(v.nb_read_frames), width: v.width, height: v.height, video_codec: v.codec_name, pix_fmt: v.pix_fmt,
    audio_codec: a.codec_name, sample_rate_hz: Number(a.sample_rate), audio_pcm_samples: pcm.stdout.length / 4,
    audio_pcm_sha256: sha256(pcm.stdout), sampled_frame_hashes: frames,
  };
}

