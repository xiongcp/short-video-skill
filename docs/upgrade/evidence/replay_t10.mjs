function makeAuditor(outDir) {
  let seq = 0;
  return {
    count: () => seq,
    async call(label, project, op, request, env = {}, session = null) {
      const n = seq++;
      const reqPath = writeJson(join(project, 'requests', `${String(n).padStart(4, '0')}-${op}.json`), request);
      const run = await runCliAsync([op, '--project', project, '--request', reqPath], env);
      writeFileSync(join(outDir, 'audit', `${String(n).padStart(3, '0')}-${label}.json`),
        JSON.stringify({ seq: n, label, op, session, request, exit_code: run.code, response: run.json }, null, 2) + '\n');
      return run;
    },
  };
}
async function rawCall(project, op, request, env = {}) {
  const reqPath = writeJson(join(project, 'requests', `setup-${Math.random().toString(36).slice(2, 10)}-${op}.json`), request);
  const run = await runCliAsync([op, '--project', project, '--request', reqPath], env);
  if (run.code !== 0) throw new Error(`${op} failed (${run.code}): ${run.stdout}${run.stderr}`);
  return run.json;
}
